export function addEntries(entries) { for (const [a,b] of entries) if(a && b) lexicon[a]=b; }
const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
let glossary;
export function translateText(text, { phrases = true } = {}) {
  const raw = String(text ?? ''); const trimmed = raw.trim();
  if (Object.hasOwn(lexicon, trimmed)) return raw.replace(trimmed, lexicon[trimmed]);
  // Never alter arbitrary names, prose or expressions by translating individual words.
  if (!phrases) return raw;
  glossary ??= Object.entries(lexicon).filter(([k])=>k.length>2 && /^[A-Za-z][A-Za-z '-]+$/.test(k)).sort((a,b)=>b[0].length-a[0].length);
  let out=raw;
  for(const [key,value] of glossary) out=out.replace(new RegExp(`(?<![A-Za-z])${esc(key)}(?![A-Za-z])`,'g'),value);
  return out;
}
